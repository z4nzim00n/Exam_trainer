/*
* EXAM_03_02. Перевод в градусную меру.
 *
 * Умножаем радианы на 57.29, округляем и выводим.
 */

#include <math.h>
#include <stdio.h>

int main(void) {
    /* Угол может быть дробным и отрицательным, поэтому double. */
    double radians;

    /*
     * %lf — формат чтения double.
     * scanf возвращает количество прочитанных значений.
     * Если не удалось прочитать число — выводим n/a и выходим.
     */
    if (scanf("%lf", &radians) != 1) {
        printf("n/a");
        return 0;
    }

    /* Перевод: градусы = радианы * 57.29 */
    double result = radians * 57.29;

    /*
     * round() округляет до ближайшего целого.
     * %.0lf выводит без дробной части.
     * Без \n — по условию.
     */
    printf("%.0lf", round(result));

    return 0;
}