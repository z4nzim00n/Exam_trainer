/* EXAM_03_03. Перестановка крайних цифр трёхзначного числа. */

#include <stdio.h>

int main(void) {
    int n;

    if (scanf("%d", &n) != 1) {
        return 1;
    }

    /* Знак запоминаем отдельно, а дальше работаем с модулем: остатки от деления не зависят от знака. */
    int negative_sign = 0;
    if (n < 0) {
        n = -n;
        negative_sign = 1;
    }

    /* % 10 даёт последнюю цифру, / 10 отбрасывает её. */
    int last = n % 10;
    n = n / 10;
    int middle = n % 10;
    n = n / 10;
    int first = n % 10;

    /* Минус не цифра, поэтому не переставляется и просто идёт перед результатом. */
    if (negative_sign) {
        putchar('-');
    }

    /* Каждая цифра печатается отдельно: если собрать число целиком, ведущий ноль пропадёт (021 -> 21). */
    printf("%d%d%d", last, middle, first);

    return 0;
}