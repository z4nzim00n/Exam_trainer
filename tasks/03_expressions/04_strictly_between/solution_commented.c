/**
 * EXAM_03_04 — Чило внутри отрезка.
 * Написаны три числа: A, B, C. Нужно вывести «1»,
 * если C лежит строго между A и B, иначе «0».
 */
#include <stdio.h>

int main(void) {
    int a, b, c;

    /* Если не удаётся прочитать все три числа — плохой ввод. */
    if (scanf("%d %d %d", &a, &b, &c) != 3) {
        printf("n/a");
        return 0;
    }

    /* C должен быть строго между a и b. Порядок не важен —
       проверяем оба и печатаем результат напрямую. */
    printf("%d", (a < c && c < b) || (b < c && c < a));

    return 0;
}
