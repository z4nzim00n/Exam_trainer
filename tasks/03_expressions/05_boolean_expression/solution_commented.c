/**
 * EXAM_03_05 — Логическое выражение.
 * Читаем три числа x, y, z (по 0 или 1). Печатаем «1»,
 * если X и (Z или Y) истинно, иначе «0».
 */
#include <stdio.h>

int main(void) {
    int x, y, z;

    /* Если не удалось прочитать все три числа — плохой ввод. */
    if (scanf("%d %d %d", &x, &y, &z) != 3) {
        printf("n/a");
        return 0;
    }

    /* Каждое должно быть ровно 0 или 1, иначе n/a. */
    if (!(x == 0 || x == 1) || !(y == 0 || y == 1) || !(z == 0 || z == 1)) {
        printf("n/a");
        return 0;
    }

    /* Вычисляем логическое выражение: Х и (Z или Y) */
    printf("%d", x && (z || y));

    return 0;
}
