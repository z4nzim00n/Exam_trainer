/*
* EXAM_03_01. Масса шара.
 *
 * Сначала находим объём шара по радиусу,
 * затем умножаем объём на плотность платины.
 */

#include <math.h>
#include <stdio.h>

int main(void) {
    /* Радиус может быть дробным, поэтому используем double. */
    double radius;

    /*
     * %lf — формат чтения double.
     * &radius — адрес переменной, куда scanf запишет число.
     *
     * scanf должна успешно прочитать одно значение и вернуть 1.
     * Отрицательный радиус недопустим.
     *
     * || означает «ИЛИ». Если чтение не удалось, правая часть
     * условия не проверяется: значение radius не используется.
     */
    if (scanf("%lf", &radius) != 1 || radius < 0) {
        printf("n/a");
        return 0;
    }

    /*
     * Объём шара: V = (4 / 3) * pi * R³.
     *
     * Пишем 4.0 / 3.0, чтобы деление было вещественным:
     * целочисленное выражение 4 / 3 дало бы 1.
     *
     * M_PI — число pi, доступное в используемой среде через math.h.
     * Куб радиуса вычисляем обычным умножением.
     */
    double V = (4.0 / 3.0) * M_PI * (radius * radius * radius);

    /*
     * Масса = плотность * объём.
     * Плотность платины — 21500 кг/м³, поэтому масса получится в кг.
     */
    double m = 21500.0 * V;

    /*
     * Округляем итоговую массу, не промежуточный объём.
     * Формат %.0lf выводит число без знаков после десятичной точки.
     */
    printf("%.0lf", round(m));

    return 0;
}