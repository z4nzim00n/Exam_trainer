/* EXAM_03_01. Масса шара: радиус -> объём -> масса. */

#include <math.h>
#include <stdio.h>

int main(void) {
    double radius;

    /* Если чтение не удалось, radius не определён: правая часть || не вычисляется. */
    if (scanf("%lf", &radius) != 1 || radius < 0) {
        printf("n/a");
        return 0;
    }

    /* 4.0 / 3.0, а не 4 / 3: целочисленное деление дало бы 1. */
    double V = (4.0 / 3.0) * M_PI * (radius * radius * radius);

    /* Плотность платины в кг/м³, радиус в метрах, поэтому масса сразу в кг. */
    double m = 21500.0 * V;

    /* Округляем только итог. round() режет по школьным правилам (0.5 вверх), %.0lf убирает ".0". */
    printf("%.0lf", round(m));

    return 0;
}