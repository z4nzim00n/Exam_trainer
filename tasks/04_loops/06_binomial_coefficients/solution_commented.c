/*
 * EXAM_04_06. Биномиальные коэффициенты.
 *
 * Факториалы не считаем: они переполняются уже при n > 20.
 * Каждый следующий коэффициент получаем из предыдущего:
 *     C(n, k + 1) = C(n, k) * (n - k) / (k + 1)
 */

#include <stdio.h>

int main(void) {
    int n;
    int ch;

    /* n должно быть целым и неотрицательным */
    if (scanf("%d", &n) != 1 || n < 0) {
        printf("n/a");
        return 0;
    }

    /* После числа допустимы только пробельные символы до конца строки */
    while ((ch = getchar()) != EOF && ch != '\n') {
        if (ch != ' ' && ch != '\t' && ch != '\r') {
            printf("n/a");
            return 0;
        }
    }

    /* C(n, 0) = 1 */
    unsigned long long c = 1;

    for (int k = 0; k <= n; k++) {
        /* Пробел только между числами, после последнего его нет */
        if (k > 0) {
            printf(" ");
        }
        printf("%llu", c);

        /*
         * Переходим к C(n, k + 1).
         * Сначала умножаем, потом делим: так деление всегда выходит без остатка.
         * На последнем шаге (k == n) множитель n - k равен 0, лишнего вывода нет.
         */
        c = c * (n - k) / (k + 1);
    }

    return 0;
}