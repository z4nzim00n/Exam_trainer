/**
 * EXAM_04_02. Поиск greatest в последовательности.
 * Читаем числа до сентинела -1, вычисляем наибольшее и печать его.
 */
#include <stdio.h>

int main(void) {
    /* Храним очередной элемент; max — текущий максимум. */
    int x;
    int max = 0;

    /* Читаем до сентинела -1. scanf проверяет успешность чтения,
       поэтому ввод не-числа прерывает цикл. */
    while (scanf("%d", &x) == 1 && x != -1) {
        /* Обновляем максимум: новый элемент превышает текущий. */
        if (x > max) {
            max = x;
        }
    }

    /* Печатаем без переноса строки. */
    printf("%d", max);
    return 0;
}
