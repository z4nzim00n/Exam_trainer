/*
* EXAM_04_05. Произведение нечётных цифр.
 *
 * Выделяем цифры числа и перемножаем только нечётные.
 * Если нечётных цифр нет, выводим 0.
 */

#include <stdio.h>

int main(void) {
    int n;

    /*
     * scanf должна прочитать одно целое число и вернуть 1.
     * При неудачном чтении выводим n/a и завершаем программу.
     */
    if (scanf("%d", &n) != 1) {
        printf("n/a");
        return 0;
    }

    /* Начинаем с единицы: она не меняет результат умножения. */
    int product = 1;

    /*
     * Флаг показывает, встретилась ли хотя бы одна нечётная цифра.
     * Он нужен, потому что product == 1 возможен и для числа 111.
     */
    int has_odd = 0;
    int digit;

    /* Обрабатываем хотя бы одну цифру, в том числе для входа 0. */
    do {
        digit = n % 10;

        /*
         * Делаем положительной только выделенную цифру.
         * В отличие от смены знака всего числа, это безопасно
         * и для минимального значения int.
         */
        if (digit < 0) {
            digit = -digit;
        }

        /* Нечётная цифра не делится на 2 без остатка. */
        if (digit % 2 != 0) {
            /* Добавляем цифру в произведение и отмечаем её наличие. */
            product *= digit;
            has_odd = 1;
        }

        /* Убираем обработанную цифру. Чётные цифры просто пропускаем. */
        n /= 10;
    } while (n != 0);

    /*
     * Если нечётные цифры были, выводим произведение.
     * Иначе выводим 0, как требует условие.
     * Перенос строки не добавляем.
     */
    if (has_odd) {
        printf("%d", product);
    } else {
        printf("0");
    }

    return 0;
}