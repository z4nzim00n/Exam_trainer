#include <stdio.h>

int main(void) {
    int n;
    int c;

    // Аналогично: если scanf не смог прочитать число вообще - n/a сразу.
    if (scanf("%d", &n) != 1) {
        printf("n/a");
        return 0;
    }

    // Дочитываем остаток строки после числа, чтобы убедиться,
    // что там нет ничего, кроме пробельных символов.
    // Именно это отличает "12abc" (мусор после числа) от "12" (чистое число).
    while ((c = getchar()) != EOF && c != '\n') {
        if (c != ' ' && c != '\t' && c != '\r') {
            printf("n/a");
            return 0;
        }
    }

    int product = 1;
    int has_odd = 0;  // флаг: встретилась ли хотя бы одна нечётная цифра

    do {
        int digit = n % 10;
        if (digit < 0) {
            digit = -digit;  // берём цифру по модулю, знак числа не важен
        }

        if (digit % 2 != 0) {
            product *= digit;
            has_odd = 1;
        }
        n /= 10;
    } while (n != 0);

    // Если нечётных цифр не встретилось вообще - по условию задачи выводим 0,
    // а не "пустое" произведение (которое было бы равно 1).
    if (has_odd) {
        printf("%d", product);
    } else {
        printf("0");
    }

    return 0;
}