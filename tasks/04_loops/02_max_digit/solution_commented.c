/*
* EXAM_04_04. Наибольшая цифра.
 *
 * Выделяем цифры числа справа налево
 * и запоминаем наибольшую.
 */

#include <stdio.h>

int main(void) {
    int n;

    /* Все цифры неотрицательные, поэтому начинаем с нуля. */
    int max = 0;

    /*
     * %d — формат чтения int.
     * Если не удалось прочитать одно число, выводим n/a.
     */
    if (scanf("%d", &n) != 1) {
        printf("n/a");
        return 0;
    }

    /*
     * do ... while выполняется хотя бы один раз:
     * даже у числа 0 обрабатываем его единственную цифру.
     */
    do {
        /* Остаток от деления на 10 выделяет последнюю цифру со знаком. */
        int digit = n % 10;

        /*
         * У отрицательного числа остаток может быть отрицательным.
         * Меняем знак только цифры, а не всего числа:
         * это безопасно даже для минимального значения int.
         */
        if (digit < 0) {
            digit = -digit;
        }

        /* Если нашли цифру больше текущего максимума, обновляем его. */
        if (digit > max) {
            max = digit;
        }

        /* Целочисленное деление на 10 убирает последнюю цифру. */
        n /= 10;
    } while (n != 0);

    /* Выводим наибольшую цифру без переноса строки. */
    printf("%d", max);
    return 0;
}