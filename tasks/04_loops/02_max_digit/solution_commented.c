#include <stdio.h>

int main(void) {
    int n;
    int max = 0;
    int c;

    // scanf сам пропускает ведущие пробелы и останавливается на первом
    // символе, который не может быть частью числа (например, букве или точке).
    // Если число вообще не удалось прочитать - сразу n/a.
    if (scanf("%d", &n) != 1) {
        printf("n/a");
        return 0;
    }

    // Проблема в том, что scanf не читает "хвост" после числа - он просто
    // оставляет его в потоке ввода. Поэтому "12abc" даёт n = 12, а "abc"
    // остаётся непрочитанным. Надо вручную проверить, что там дальше.
    while ((c = getchar()) != EOF && c != '\n') {
        // Разрешаем только пробельные символы после числа.
        // Если встретили что-то другое (букву, точку и т.п.) - это мусор.
        if (c != ' ' && c != '\t' && c != '\r') {
            printf("n/a");
            return 0;
        }
    }

    // Дальше - обычный поиск максимальной цифры числа.
    do {
        int digit = n % 10;
        if (digit < 0) {
            digit = -digit;  // учитываем отрицательные числа
        }
        if (digit > max) {
            max = digit;
        }
        n /= 10;
    } while (n != 0);

    printf("%d", max);
    return 0;
}