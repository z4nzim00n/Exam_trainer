#include <stdio.h>

int main(void) {
    int value;

    /* Ноль не изменяет другое число при операции XOR. */
    int result = 0;

    /* -1 завершает последовательность и не участвует в вычислении. */
    while (scanf("%d", &value) == 1 && value != -1) {
        /*
         * Одинаковые числа взаимно уничтожаются при XOR.
         * После обработки всей последовательности останется
         * единственное число, которое встретилось один раз.
         */
        result ^= value;
    }

    /* Без пробела и перевода строки. */
    printf("%d", result);
    return 0;
}