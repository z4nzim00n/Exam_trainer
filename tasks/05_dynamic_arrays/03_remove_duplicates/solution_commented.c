/*
 * EXAM_05_04. Удаление повторов.
 *
 * Сохраняем только первое появление каждого числа.
 * Новые числа добавляем в конец динамического массива,
 * поэтому порядок первых вхождений сохраняется.
 */

#include <stdio.h>
#include <stdlib.h>

int main(void) {
    /* Пока память не выделена, указатель равен NULL. */
    int *array = NULL;

    /* Количество сохранённых уникальных чисел. */
    int size = 0;

    /* Начальное значение нужно для проверки после неудачного чтения. */
    int value = 0;

    /* Читаем числа до ошибки чтения или признака конца -1. */
    while (scanf("%d", &value) == 1 && value != -1) {
        /* -1 уже исключено условием цикла, другие отрицательные запрещены. */
        if (value < 0) {
            free(array);
            printf("n/a");
            return 0;
        }

        /* Флаг: встречалось ли текущее число среди сохранённых. */
        int found = 0;

        for (int i = 0; i < size; i++) {
            if (array[i] == value) {
                found = 1;

                /* Совпадение найдено — дальнейший поиск не нужен. */
                break;
            }
        }

        /* Добавляем только число, которого ещё нет в массиве. */
        if (!found) {
            /*
             * Расширяем массив на один элемент.
             * При array == NULL realloc работает как malloc.
             *
             * Временный указатель нужен, чтобы при ошибке
             * не потерять адрес ранее выделенной памяти.
             */
            int *temp = realloc(array, (size + 1) * sizeof(int));

            if (temp == NULL) {
                free(array);
                printf("n/a");
                return 0;
            }

            array = temp;

            /* Индекс size — место для нового элемента. */
            array[size] = value;
            size++;
        }
    }

    /*
     * Корректный конец последовательности — только -1.
     * Если чтение прервалось раньше, выводим n/a.
     */
    if (value != -1) {
        free(array);
        printf("n/a");
        return 0;
    }

    /*
     * Выводим результат после проверки всего ввода до -1.
     * Пробел ставим перед каждым элементом, кроме первого.
     */
    for (int i = 0; i < size; i++) {
        if (i > 0) {
            printf(" ");
        }

        printf("%d", array[i]);
    }

    /*
     * Для пустой последовательности цикл вывода не выполняется.
     * free(NULL) допустим и ничего не делает.
     */
    free(array);

    return 0;
}