/*
 * EXAM_05_03. Вывод последовательности.
 *
 * Читаем неотрицательные числа до -1 в динамический массив.
 * Затем выводим их навстречу друг другу:
 * первый, последний, второй, предпоследний и т.д.
 */

#include <stdio.h>
#include <stdlib.h>

int main(void) {
    int *array = NULL;
    int size = 0;
    int value = 0;

    /*
     * Читаем числа по одному.
     * Цикл идёт, пока ввод корректен и не встретилось -1.
     */
    while (scanf("%d", &value) == 1 && value != -1) {
        /* Все элементы последовательности должны быть неотрицательными */
        if (value < 0) {
            free(array);
            printf("n/a");
            return 0;
        }

        /*
         * realloc увеличивает размер памяти под еще один int.
         * Всегда сохраняем результат во временный указатель temp:
         * если памяти не хватит, старый array не потеряется.
         */
        int *temp = realloc(array, (size + 1) * sizeof(int));

        if (temp == NULL) {
            free(array);
            printf("n/a");
            return 0;
        }

        array = temp;
        array[size] = value;
        size++;
    }

    /*
     * Проверяем, как именно завершился цикл:
     * 1. Если value != -1, значит ввод оборвался на букве или EOF без -1.
     * 2. Если size == 0, значит последовательность пустая (сразу ввели -1).
     * В обоих случаях это ошибка.
     */
    if (value != -1 || size == 0) {
        free(array);
        printf("n/a");
        return 0;
    }

    /*
     * Метод двух указателей:
     * left идёт от начала вправо (0, 1, 2...),
     * right идёт от конца влево (size-1, size-2...).
     */
    int left = 0;
    int right = size - 1;
    int first = 1;

    while (left <= right) {
        /* Пробел печатаем перед числом (начиная со второго вывода) */
        if (!first) {
            printf(" ");
        }

        printf("%d", array[left]);
        first = 0;

        /*
         * Если остался один центральный элемент (left == right),
         * второй раз его выводить не нужно.
         */
        if (left != right) {
            printf(" %d", array[right]);
        }

        left++;
        right--;
    }

    /* Обязательно освобождаем память */
    free(array);

    return 0;
}