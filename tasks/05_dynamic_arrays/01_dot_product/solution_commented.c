/*
 * EXAM_05_01. Скалярное произведение.
 *
 * Читаем размерность n, выделяем память под первый вектор,
 * читаем его координаты.
 * Координаты второго вектора читаем по одной «на лету»,
 * сразу умножая на соответствующий элемент первого вектора.
 */

#include <stdio.h>
#include <stdlib.h>

int main(void) {
    int n;

    /* Читаем размерность. Число должно быть строго больше нуля. */
    if (scanf("%d", &n) != 1 || n <= 0) {
        printf("n/a");
        return 0;
    }

    /*
     * Выделяем память в куче под n элементов типа int.
     * malloc возвращает указатель на начало выделенного блока.
     */
    int *a = malloc(n * sizeof(int));

    /* Если операционная система не смогла выделить память — выходим. */
    if (a == NULL) {
        printf("n/a");
        return 0;
    }

    /* Читаем координаты первого вектора */
    for (int i = 0; i < n; i++) {
        if (scanf("%d", &a[i]) != 1) {
            /* Обязательно освобождаем память перед выходом! */
            free(a);
            printf("n/a");
            return 0;
        }
    }

    /*
     * long long гарантирует 64 бита (числа до ~9 квинтиллионов),
     * поэтому сумма произведений точно не переполнится.
     */
    long long sum = 0;
    int temp;

    /*
     * Читаем координаты второго вектора.
     * Хранить весь второй вектор в памяти не нужно:
     * прочитали temp -> умножили на a[i] -> прибавили к сумме.
     */
    for (int i = 0; i < n; i++) {
        if (scanf("%d", &temp) != 1) {
            free(a);
            printf("n/a");
            return 0;
        }

        /*
         * (long long)a[i] расширяет первый множитель до 64 бит.
         * Умножение выполняется уже в long long, а не в int,
         * поэтому результат не сломается от переполнения.
         */
        sum += (long long)a[i] * temp;
    }

    /* Освобождаем выделенную память после всех вычислений */
    free(a);

    /* Вывод результата (%lld для типа long long) без переноса строки */
    printf("%lld", sum);

    return 0;
}