/*
* EXAM_05_05. Реверс последовательности.
 *
 * Сохраняем числа до -1 в динамический массив.
 * Затем выводим массив от последнего элемента к первому.
 */

#include <stdio.h>
#include <stdlib.h>

int main(void) {
    /* Память пока не выделена, элементов нет. */
    int *array = NULL;
    int size = 0;

    /* Начальное значение нужно для проверки, если первое чтение не удалось. */
    int value = 0;

    /* Читаем числа, пока чтение успешно и не встретилось -1. */
    while (scanf("%d", &value) == 1 && value != -1) {
        /* Другие отрицательные числа не могут быть элементами. */
        if (value < 0) {
            free(array);
            printf("n/a");
            return 0;
        }

        /*
         * Расширяем массив на один int.
         * При array == NULL realloc выделяет новый блок.
         * Результат сохраняем отдельно, чтобы при ошибке
         * не потерять указатель на прежнюю память.
         */
        int *temp = realloc(array, (size + 1) * sizeof(int));

        if (temp == NULL) {
            free(array);
            printf("n/a");
            return 0;
        }

        array = temp;

        /*
         * Записываем число по текущему индексу size,
         * затем увеличиваем количество элементов на один.
         */
        array[size++] = value;
    }

    /* Если -1 не прочитано, ввод завершился некорректно. */
    if (value != -1) {
        free(array);
        printf("n/a");
        return 0;
    }

    /*
     * Последний элемент имеет индекс size - 1.
     * Уменьшаем индекс до нуля включительно.
     */
    for (int i = size - 1; i >= 0; i--) {
        /* Перед первым выводимым элементом пробел не нужен. */
        if (i < size - 1) {
            printf(" ");
        }

        printf("%d", array[i]);
    }

    /*
     * Для пустой последовательности цикл вывода не выполняется.
     * free(NULL) допустим и ничего не делает.
     */
    free(array);

    return 0;
}