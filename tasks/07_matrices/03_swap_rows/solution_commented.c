/*
 * EXAM_06_02. Перестановка строк.
 *
 * Читаем матрицу M x N в одномерный массив.
 * Находим строки с первым вхождением минимума и максимума.
 * Меняем эти строки местами и выводим результат.
 */

#include <stdio.h>
#include <stdlib.h>

int main(void) {
    int m, n;

    /* Читаем размеры. Оба должны быть строго положительными. */
    if (scanf("%d %d", &m, &n) != 2 || m <= 0 || n <= 0) {
        printf("n/a");
        return 0;
    }

    /* Выделяем память под M * N элементов. (size_t) защищает от переполнения. */
    int *matrix = malloc((size_t)m * n * sizeof(int));

    if (matrix == NULL) {
        printf("n/a");
        return 0;
    }

    /* Читаем элементы матрицы построчно */
    for (int i = 0; i < m * n; i++) {
        if (scanf("%d", &matrix[i]) != 1) {
            free(matrix);
            printf("n/a");
            return 0;
        }
    }

    /* Инициализируем min и max первым элементом матрицы */
    int min = matrix[0];
    int max = matrix[0];
    int min_row = 0;
    int max_row = 0;

    /*
     * Проходим по всем элементам, начиная со второго.
     * Индекс строки в одномерном массиве вычисляется как i / n.
     */
    for (int i = 1; i < m * n; i++) {
        /*
         * Используем строгое неравенство (<).
         * Если встретится такой же минимум, условие не сработает,
         * и мы сохраним индекс ПЕРВОГО вхождения.
         */
        if (matrix[i] < min) {
            min = matrix[i];
            min_row = i / n;
        }

        /* Аналогично для максимума: строгое (>) сохраняет первое вхождение. */
        if (matrix[i] > max) {
            max = matrix[i];
            max_row = i / n;
        }
    }

    /*
     * Меняем местами строки min_row и max_row.
     * Проходим по всем столбцам j от 0 до n-1.
     * Если min_row == max_row, элементы просто поменяются местами сами с собой.
     */
    for (int j = 0; j < n; j++) {
        int temp = matrix[min_row * n + j];
        matrix[min_row * n + j] = matrix[max_row * n + j];
        matrix[max_row * n + j] = temp;
    }

    /* Выводим результирующую матрицу */
    for (int i = 0; i < m; i++) {
        for (int j = 0; j < n; j++) {
            /* Пробел только между числами, в конце строки пробела нет */
            if (j > 0) {
                printf(" ");
            }
            printf("%d", matrix[i * n + j]);
        }

        /* Перенос строки после каждой строки матрицы, кроме самой последней */
        if (i < m - 1) {
            printf("\n");
        }
    }

    /* Освобождаем память */
    free(matrix);

    return 0;
}