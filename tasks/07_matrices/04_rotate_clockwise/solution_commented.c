/*
 * EXAM_06_03. Поворот матрицы.
 *
 * Читаем матрицу M x N в одномерный массив.
 * При выводе используем математическую формулу для пересчёта индексов,
 * чтобы напечатать матрицу повёрнутой на 90 градусов по часовой стрелке,
 * не выделяя память под второй массив.
 */

#include <stdio.h>
#include <stdlib.h>

int main(void) {
    int m, n;

    /* Читаем размеры исходной матрицы: M строк, N столбцов. */
    if (scanf("%d %d", &m, &n) != 2 || m <= 0 || n <= 0) {
        printf("n/a");
        return 0;
    }

    /* Выделяем память под M * N элементов. */
    int *matrix = malloc((size_t)m * n * sizeof(int));

    if (matrix == NULL) {
        printf("n/a");
        return 0;
    }

    /* Заполняем матрицу. При ошибке ввода освобождаем память и выходим. */
    for (int i = 0; i < m * n; i++) {
        if (scanf("%d", &matrix[i]) != 1) {
            free(matrix);
            printf("n/a");
            return 0;
        }
    }

    /*
     * Повёрнутая матрица будет иметь размер N строк на M столбцов.
     * Внешний цикл i идёт по строкам новой матрицы (от 0 до N-1).
     * Внутренний цикл j идёт по столбцам новой матрицы (от 0 до M-1).
     */
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            if (j > 0) {
                printf(" ");
            }
            
            /*
             * Вычисляем, откуда взять элемент из ИСХОДНОЙ матрицы:
             * Столбец новой матрицы (i) становится строкой старой.
             * Строка новой матрицы (j) становится столбцом старой, но в обратном порядке.
             */
            int orig_row = m - 1 - j;
            int orig_col = i;
            
            /* Формула индекса для одномерного массива: row * N + col */
            printf("%d", matrix[orig_row * n + orig_col]);
        }
        
        /* Перенос строки после каждой строки, кроме последней */
        if (i < n - 1) {
            printf("\n");
        }
    }

    /* Освобождаем память */
    free(matrix);

    return 0;
}