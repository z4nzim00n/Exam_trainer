/*
 * EXAM_06_01. Умножение квадратных матриц.
 *
 * Читаем размерность n, выделяем память под три матрицы (A, B и C).
 * Заполняем A и B, перемножаем их и выводим результат C.
 * Матрицы хранятся в виде одномерных динамических массивов.
 */

#include <stdio.h>
#include <stdlib.h>

int main(void) {
    int n;

    /* Читаем размерность. Она должна быть строго больше нуля. */
    if (scanf("%d", &n) != 1 || n <= 0) {
        printf("n/a");
        return 0;
    }

    /*
     * Выделяем память под n*n элементов для каждой матрицы.
     * Приведение (size_t) защищает от переполнения int при больших n.
     */
    int *a = malloc((size_t)n * n * sizeof(int));
    int *b = malloc((size_t)n * n * sizeof(int));
    int *c = malloc((size_t)n * n * sizeof(int));

    /* Если хотя бы один массив не удалось создать — освобождаем всё и выходим. */
    if (a == NULL || b == NULL || c == NULL) {
        free(a);
        free(b);
        free(c);
        printf("n/a");
        return 0;
    }

    /* Читаем элементы матрицы A */
    for (int i = 0; i < n * n; i++) {
        if (scanf("%d", &a[i]) != 1) {
            free(a); free(b); free(c);
            printf("n/a");
            return 0;
        }
    }

    /* Читаем элементы матрицы B */
    for (int i = 0; i < n * n; i++) {
        if (scanf("%d", &b[i]) != 1) {
            free(a); free(b); free(c);
            printf("n/a");
            return 0;
        }
    }

    /*
     * Умножение матриц: C = A * B
     * Элемент C[i][j] равен сумме произведений элементов i-й строки A на j-й столбец B.
     * Индекс в одномерном массиве вычисляется как: row * n + col.
     */
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            c[i * n + j] = 0; /* Обнуляем перед накоплением суммы */
            for (int k = 0; k < n; k++) {
                c[i * n + j] += a[i * n + k] * b[k * n + j];
            }
        }
    }

    /* Вывод результирующей матрицы C */
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            /* Пробел только между числами, перед первым числом пробела нет */
            if (j > 0) {
                printf(" ");
            }
            printf("%d", c[i * n + j]);
        }
        /* Перенос строки после каждой строки матрицы, кроме последней */
        if (i < n - 1) {
            printf("\n");
        }
    }

    /* Освобождаем всю выделенную память */
    free(a);
    free(b);
    free(c);

    return 0;
}