#include <stdio.h>  // fgets, printf, stdin

int main(void) {
    // Буфер под строку: 100 символов по условию + '\n' + '\0' = 102 байта.
    char str[102];

    // Флаг-ответ. Начинаем с 0: пока строка не прочитана
    // и не проверена, идентификатором она не считается.
    int is_identifier = 0;

    // Читаем строку. Условие состоит из двух частей через &&:
    //   1) fgets не вернул NULL (ввод не пуст, сразу не EOF);
    //   2) первый символ не '\n' (строка не пустая).
    // Если первая часть ложна, до str[0] дело не дойдёт:
    // && останавливается на первом ложном условии,
    // поэтому неинициализированный массив не читается.
    if (fgets(str, sizeof str, stdin) != NULL && str[0] != '\n') {
        // Строка непустая, значит, она может быть идентификатором.
        // Дальше цикл попробует это опровергнуть.
        is_identifier = 1;

        // Идём по символам до '\0' или '\n'.
        // '\n' не входит в строку и в проверке не участвует.
        for (int i = 0; str[i] != '\0' && str[i] != '\n'; i++) {
            // 1, если символ - латинская буква любого регистра.
            int letter = (str[i] >= 'a' && str[i] <= 'z') || (str[i] >= 'A' && str[i] <= 'Z');

            // 1, если символ - цифра.
            int number = str[i] >= '0' && str[i] <= '9';

            // 1, если символ - знак подчёркивания.
            int under = str[i] == '_';

            // Ошибка, если одновременно:
            //   - не буква;
            //   - не подчёркивание;
            //   - не "цифра не на первой позиции".
            // Допустимые символы: буква и '_' на любой позиции,
            // цифра на любой позиции, кроме первой.
            if (!letter && !under && !(number && i != 0)) {
                is_identifier = 0;
                break;  // дальше проверять нет смысла
            }
        }
    }

    // Тернарный оператор: флаг 1 - выводим "Yes", иначе "No".
    // printf без '\n', как требует условие.
    printf("%s", is_identifier ? "Yes" : "No");

    // Успешное завершение программы.
    return 0;
}