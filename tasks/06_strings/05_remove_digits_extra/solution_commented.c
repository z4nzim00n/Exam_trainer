#include <stdio.h>

int main(void) {
    /* getchar возвращает код символа или EOF, поэтому нужен int. */
    int ch;

    /* Читаем до перевода строки или конца ввода. */
    while ((ch = getchar()) != EOF && ch != '\n') {
        /*
         * Цифры занимают диапазон от '0' до '9'.
         * Выводим символ, только если он находится вне этого диапазона.
         */
        if (ch < '0' || ch > '9') {
            /* Пробелы, буквы и знаки препинания сохраняем как есть. */
            putchar(ch);
        }
    }

    /* Завершающий перевод строки не добавляем. */
    return 0;
}