#include <stdio.h>   // fgets, fputs, stdin, stdout
#include <string.h>  // strstr, strlen, strcspn, memmove

// Максимальные длины по условию задачи.
#define MAX_TEXT 200  // основная строка: до 200 символов
#define MAX_SUB 100   // подстрока: до 100 символов

int main(void) {
    // Буфер под основную строку: 200 символов + '\n' + '\0'.
    // "" обнуляет весь массив: если ввод пустой и fgets ничего
    // не запишет, в массиве будет корректная пустая строка.
    char str[MAX_TEXT + 2] = "";

    // То же самое для подстроки: 100 символов + '\n' + '\0'.
    char sub[MAX_SUB + 2] = "";

    // Читаем первую строку (до '\n' или до конца ввода).
    // sizeof str — размер массива в байтах, fgets не выйдет за него.
    fgets(str, sizeof str, stdin);

    // Читаем вторую строку (подстроку) так же.
    fgets(sub, sizeof sub, stdin);

    // Ищем в str первый '\n' и заменяем его на '\0'.
    // Если '\n' нет (EOF), strcspn вернёт длину строки,
    // и мы запишем '\0' туда, где он уже стоит.
    str[strcspn(str, "\n")] = '\0';

    // То же самое для подстроки.
    sub[strcspn(sub, "\n")] = '\0';

    // Длина подстроки: считаем один раз, дальше она нужна дважды.
    size_t len = strlen(sub);

    // Здесь будем хранить адрес последнего вхождения.
    // NULL означает "ничего не найдено".
    char *last = NULL;

    // p — текущая позиция, с которой ищем. Начинаем с начала строки.
    char *p = str;

    // Пустую подстроку не ищем: strstr "находит" её в каждой позиции,
    // а по условию такая подстрока ничего не меняет.
    if (len > 0) {
        // strstr ищет sub в строке, начиная с p.
        // Возвращает адрес вхождения или NULL, если больше нет.
        // Присваиваем результат p и сразу проверяем на NULL.
        while ((p = strstr(p, sub)) != NULL) {
            // Нашли вхождение: запоминаем его как "последнее на данный момент".
            last = p;

            // Сдвигаемся на один символ вперёд, чтобы искать дальше
            // и не пропустить пересекающиеся вхождения (aaa и aa).
            p++;
        }
    }

    // Если вхождение найдено, удаляем его.
    if (last != NULL) {
        // last + len — первый символ после удаляемого фрагмента (начало хвоста).
        // strlen(last + len) + 1 — длина хвоста вместе с завершающим '\0'.
        // Копируем хвост на место фрагмента (со сдвигом влево).
        // memmove безопасен при пересечении областей, strcpy — нет.
        memmove(last, last + len, strlen(last + len) + 1);
    }

    // Выводим результат без '\n' в конце.
    // fputs, в отличие от puts, не добавляет перенос строки.
    fputs(str, stdout);

    // Успешное завершение программы.
    return 0;
}