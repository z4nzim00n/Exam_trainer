#include <stdio.h>

int main(void) {
    int shift;
    int ch;

    /* По условию сдвиг — целое число от 0 до 25. */
    if (scanf("%d", &shift) != 1) {
        return 0;
    }

    /*
     * scanf оставляет перевод строки во входном потоке.
     * По условию он находится сразу после числа.
     */
    getchar();

    /* Читаем текст до перевода строки или EOF. */
    while ((ch = getchar()) != EOF && ch != '\n') {
        if (ch >= 'a' && ch <= 'z') {
            /*
             * Получаем номер буквы от 0 до 25, прибавляем сдвиг,
             * возвращаемся в пределы алфавита и получаем новую букву.
             */
            ch = 'a' + (ch - 'a' + shift) % 26;
        } else if (ch >= 'A' && ch <= 'Z') {
            /* Заглавные буквы обрабатываем в своём диапазоне. */
            ch = 'A' + (ch - 'A' + shift) % 26;
        }

        /* Небуквенные символы выводятся без изменений. */
        putchar(ch);
    }

    return 0;
}