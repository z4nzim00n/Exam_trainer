#include <stdio.h>

int main(void) {
    /* Массив для очищенной строки: только буквы и цифры в нижнем регистре. */
    char s[102];
    int n = 0;
    int ch;

    /* Читаем до перевода строки или конца ввода. */
    while ((ch = getchar()) != EOF && ch != '\n') {
        /* Пробелы игнорируем. */
        if (ch == ' ') {
            continue;
        }

        /* Заглавные буквы переводим в строчные. */
        if (ch >= 'A' && ch <= 'Z') {
            s[n++] = (char)(ch - 'A' + 'a');
        }
        /* Строчные буквы и цифры сохраняем как есть. */
        else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) {
            s[n++] = (char)ch;
        }
    }

    /* Если после фильтрации ничего не осталось — не палиндром. */
    if (n == 0) {
        printf("NO");
        return 0;
    }

    /* Два указателя: с начала и с конца очищенной строки. */
    int l = 0;
    int r = n - 1;
    int ok = 1;

    while (l < r) {
        if (s[l] != s[r]) {
            ok = 0;
            break;
        }
        l++;
        r--;
    }

    /* Выводим YES или NO без переноса строки. */
    printf("%s", ok ? "YES" : "NO");
    return 0;
}