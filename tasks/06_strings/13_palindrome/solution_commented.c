#include <stdio.h>  // fgets, printf, stdin

int main(void) {
    // Буфер под строку: 100 символов + '\n' + '\0' = 102 байта.
    char c[102];

    // Длина строки без '\n'. Считаем вручную, без strlen.
    int len = 0;

    // Читаем строку. fgets вернёт NULL, если ввод пуст (сразу EOF).
    // В этом случае массив c не трогаем, а len остаётся 0.
    if (fgets(c, sizeof(c), stdin) != NULL) {
        // Идём по строке до '\0' или до '\n'.
        // '\n' не входит в строку и в проверке не участвует.
        for (int i = 0; c[i] != '\0' && c[i] != '\n'; i++) {
            // Если символ - заглавная латинская буква...
            if (c[i] >= 'A' && c[i] <= 'Z') {
                // ...переводим в строчную. Разница между 'a' и 'A'
                // одинакова для всех букв, поэтому прибавляем её.
                c[i] = c[i] - 'A' + 'a';
            }
            // Считаем символ частью строки.
            len++;
        }
    }

    // l - левый указатель (индекс), начинаем с первого символа.
    int l = 0;

    // r - правый указатель, начинаем с последнего символа строки.
    // Для пустой строки r = -1, и цикл ниже не запустится.
    int r = len - 1;

    // Идём навстречу друг другу, пока указатели не встретятся
    // или не разминутся. Средний символ (если длина нечётная)
    // сам с собой сравнивать не нужно.
    while (l < r) {
        // Символы не совпали - это точно не палиндром.
        if (c[l] != c[r]) {
            // Выводим ответ без '\n', как требует условие.
            printf("NO");
            // Сразу выходим: дальше проверять нечего.
            return 0;
        }
        // Сдвигаем левый указатель вправо.
        l++;
        // Сдвигаем правый указатель влево.
        r--;
    }

    // Дошли до конца без несовпадений - строка палиндром.
    printf("YES");

    // Успешное завершение программы.
    return 0;
}
