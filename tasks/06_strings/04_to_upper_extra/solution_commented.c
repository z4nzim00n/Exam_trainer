#include <stdio.h>

int main(void) {
    /* getchar возвращает код символа или EOF. */
    int ch;

    while ((ch = getchar()) != EOF && ch != '\n') {
        /* Преобразуем только строчные латинские буквы. */
        if (ch >= 'a' && ch <= 'z') {
            /*
             * Получаем номер строчной буквы и переносим
             * его в диапазон заглавных букв.
             */
            ch = ch - 'a' + 'A';
        }

        /* Цифры, пробелы и знаки препинания остаются прежними. */
        putchar(ch);
    }

    return 0;
}