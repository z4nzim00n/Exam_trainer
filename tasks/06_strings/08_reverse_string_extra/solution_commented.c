#include <stdio.h>

int main(void) {
    /* 100 символов + '\n' + '\0' */
    char str[102];
    int len = 0;
    int ch;

    /*
     * Читаем строку посимвольно до перевода строки или EOF.
     * Это гарантирует, что мы не пропустим пробелы.
     */
    while ((ch = getchar()) != EOF && ch != '\n') {
        if (len < 101) {
            str[len] = (char)ch;
            len++;
        }
    }
    /* Завершаем строку нулевым символом */
    str[len] = '\0';

    /*
     * Выводим символы с конца.
     * Индекс последнего символа: len - 1.
     * Двигаемся вниз до индекса 0 включительно.
     */
    for (int i = len - 1; i >= 0; i--) {
        putchar(str[i]);
    }

    /* Дополнительный перевод строки в конце не печатаем */
    return 0;
}