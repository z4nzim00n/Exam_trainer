#include <stdio.h>

int main(void) {
    /* getchar возвращает код символа или EOF, поэтому используем int. */
    int ch;

    /* Был ли уже выведен хотя бы один непробельный символ. */
    int has_text = 0;

    /* Нужно ли вывести пробел перед следующим непробельным символом. */
    int pending_space = 0;

    /* Читаем до перевода строки или конца ввода. */
    while ((ch = getchar()) != EOF && ch != '\n') {
        /*
         * Пробельным считается и обычный пробел, и табуляция.
         * Обрабатываем их одинаково.
         */
        if (ch == ' ' || ch == '\t') {
            /*
             * Начальные пробельные символы игнорируем.
             * После текста запоминаем, но пока не выводим.
             * Несколько подряд оставляют флаг равным 1.
             */
            if (has_text) {
                pending_space = 1;
            }
        } else {
            /*
             * После разделителей появился новый текст.
             * Значит, между частями текста нужен ровно один
             * обычный пробел — даже если во входе была табуляция.
             */
            if (pending_space) {
                putchar(' ');
                pending_space = 0;
            }

            /* Все непробельные символы выводим без изменений. */
            putchar(ch);
            has_text = 1;
        }
    }

    /*
     * Отложенный разделитель в конце строки не выводим.
     * Перенос строки тоже не добавляем.
     */
    return 0;
}