#include <stdio.h>

int main(void) {
    /* int позволяет хранить как код символа, так и EOF. */
    int ch;

    /* Завершающий перевод строки не попадает в обработку. */
    while ((ch = getchar()) != EOF && ch != '\n') {
        /* Меняем только заглавные латинские буквы. */
        if (ch >= 'A' && ch <= 'Z') {
            /*
             * Находим позицию буквы относительно 'A'
             * и переносим её в диапазон строчных букв.
             */
            ch = ch - 'A' + 'a';
        }

        /* Остальные символы выводятся без изменений. */
        putchar(ch);
    }

    return 0;
}