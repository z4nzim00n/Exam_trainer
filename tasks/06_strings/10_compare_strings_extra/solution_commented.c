#include <stdio.h>

/* Читаем одну строку и убираем завершающий перевод строки. */
static void read_line(char str[], int size) {
    /*
     * При успешном чтении fgets добавляет '\0'.
     * Если символов прочитать не удалось, создаём пустую строку.
     */
    if (fgets(str, size, stdin) == NULL) {
        str[0] = '\0';
    }

    int i = 0;

    /* Ищем перевод строки или уже существующий конец строки. */
    while (str[i] != '\0' && str[i] != '\n') {
        i++;
    }

    /*
     * Заменяем '\n' на '\0'.
     * Если встретили '\0', просто записываем его повторно.
     */
    str[i] = '\0';
}

int main(void) {
    /* 100 символов текста + возможный '\n' + завершающий '\0'. */
    char first[102];
    char second[102];

    read_line(first, sizeof(first));
    read_line(second, sizeof(second));

    int i = 0;

    /*
     * Пропускаем совпадающие символы.
     * Останавливаемся на первом различии или конце первой строки.
     */
    while (first[i] != '\0' && first[i] == second[i]) {
        i++;
    }

    /*
     * Если строки равны, здесь обе содержат '\0'.
     * Иначе символы различаются, в том числе при разной длине строк.
     * Оператор == даёт 1 при равенстве и 0 при неравенстве.
     */
    printf("%d", first[i] == second[i]);

    return 0;
}