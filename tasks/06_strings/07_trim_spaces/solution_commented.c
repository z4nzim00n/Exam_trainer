#include <stdio.h>

int main(void) {
    /* getchar возвращает код символа или EOF, поэтому используем int. */
    int ch;

    /* Был ли уже выведен хотя бы один непробельный символ. */
    int has_text = 0;

    /* Нужно ли вывести пробел перед следующим непробельным символом. */
    int pending_space = 0;

    /* Перевод строки завершает ввод, но сам не обрабатывается. */
    while ((ch = getchar()) != EOF && ch != '\n') {
        if (ch == ' ') {
            /*
             * Начальные пробелы игнорируем.
             * Пробел после текста запоминаем, но пока не выводим.
             * Несколько пробелов подряд оставляют флаг равным 1.
             */
            if (has_text) {
                pending_space = 1;
            }
        } else {
            /*
             * После пробелов появился новый текст:
             * теперь между частями текста нужен ровно один пробел.
             */
            if (pending_space) {
                putchar(' ');
                pending_space = 0;
            }

            /* Все непробельные символы выводим без изменений. */
            putchar(ch);
            has_text = 1;
        }
    }

    /*
     * Отложенный пробел в конце строки не выводим.
     * Перенос строки также не добавляем.
     */
    return 0;
}