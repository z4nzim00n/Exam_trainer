/*
 * EXAM_06_15. Идентификатор.
 *
 * Читаем строку в массив, затем проверяем каждый символ.
 * Правило: буква или '_' подходят везде, цифра - везде, кроме первой позиции.
 */

#include <stdio.h>

int main(void) {
    char s[102]; /* до 100 символов + запас */
    int n = 0;
    int ch;

    /* Читаем до '\n' или конца ввода */
    while ((ch = getchar()) != EOF && ch != '\n') {
        s[n++] = (char)ch;
    }

    /* Пустая строка идентификатором не является */
    int ok = n > 0;

    for (int i = 0; i < n; i++) {
        int letter = (s[i] >= 'a' && s[i] <= 'z') || (s[i] >= 'A' && s[i] <= 'Z');
        int digit = s[i] >= '0' && s[i] <= '9';

        /* Подходит: буква, '_' или цифра не на первом месте */
        if (!(letter || s[i] == '_' || (digit && i > 0))) {
            ok = 0;
            break;
        }
    }

    /* Без '\n' в конце ответа */
    printf("%s", ok ? "Yes" : "No");
    return 0;
}