#include <stdio.h>  // getchar, printf, EOF

int main(void) {
    // Буфер под строку: 100 символов по условию + запас.
    // Как C-строку мы его не используем ('\0' не нужен),
    // поэтому длину храним отдельно в n.
    char s[102];

    // Сколько символов прочитано (то есть длина строки без '\n').
    int n = 0;

    // Сюда getchar() кладёт результат. Тип int, а не char:
    // кроме кодов символов он может вернуть EOF (обычно -1),
    // и в char это значение нельзя надёжно отличить от символа.
    int ch;

    // Флаг-ответ. Начинаем с 0: пока ничего не прочитано,
    // строка идентификатором не считается (пустая строка = No).
    int is_identifier = 0;

    // Читаем по одному символу, пока не встретим конец ввода или '\n'.
    // Присваивание и сравнение с EOF делаются в одном условии.
    while ((ch = getchar()) != EOF && ch != '\n') {
        // Кладём символ в массив и увеличиваем длину.
        s[n++] = ch;

        // Прочитан хотя бы один символ: строка непустая,
        // значит, она может быть идентификатором.
        // Флаг включается на первой же итерации.
        is_identifier = 1;
    }

    // Проверяем каждый символ по очереди.
    // Для пустой строки n = 0, цикл не выполнится,
    // и флаг останется 0 (результат No).
    for (int i = 0; i < n; i++) {
        // 1, если символ - латинская буква любого регистра.
        int letter = (s[i] >= 'a' && s[i] <= 'z') || (s[i] >= 'A' && s[i] <= 'Z');

        // 1, если символ - цифра.
        int digit = s[i] >= '0' && s[i] <= '9';

        // Допустимые символы:
        //   - буква (на любой позиции);
        //   - '_' (на любой позиции);
        //   - цифра, но только НЕ на первой позиции (i > 0).
        // Всё остальное (пробел, '-', '.', первая цифра...) - ошибка.
        if (!(letter || s[i] == '_' || (digit && i > 0))) {
            // Нашли недопустимый символ: это не идентификатор.
            is_identifier = 0;

            // Дальше проверять нет смысла.
            break;
        }
    }

    // Тернарный оператор: если флаг 1 - выводим "Yes", иначе "No".
    // printf без '\n', как требует условие.
    printf("%s", is_identifier ? "Yes" : "No");

    // Успешное завершение программы.
    return 0;
}