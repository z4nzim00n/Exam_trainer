/*
 * Сортировка студентов по баллам.
 *
 * Читаем студентов так же, как в задании про средний балл,
 * сортируем по убыванию оценки и выводим имена через запятую.
 */

#include <stdio.h>

/* Структура: имя и оценка. */
typedef struct {
    char name[100]; /* 99 символов + '\0' */
    int rate;
} Student;

int main(void) {
    int n;

    if (scanf("%d", &n) != 1 || n < 1) {
        printf("n/a");
        return 0;
    }

    Student students[n];

    for (int i = 0; i < n; i++) {
        /* У name нет &: имя массива уже адрес. У rate & нужен. */
        if (scanf("%99s", students[i].name) != 1 || scanf("%d", &students[i].rate) != 1) {
            printf("n/a");
            return 0;
        }
    }

    /*
     * Пузырьковая сортировка. Внутренний цикл сравняет соседей
     * и сдвигает меньшую оценку вправо. После каждого прохода
     * самый "лёгкий" элемент оказывается в конце, поэтому
     * внутренний цикл с каждым проходом короче (n - i - 1).
     */
    for (int i = 0; i < n - 1; i++) {
        for (int j = 0; j < n - i - 1; j++) {
            /*
             * Строго "меньше": при равных оценках обмена нет,
             * значит порядок ввода сохраняется.
             */
            if (students[j].rate < students[j + 1].rate) {
                /* Меняем местами целые структуры через временную переменную. */
                Student temp = students[j];
                students[j] = students[j + 1];
                students[j + 1] = temp;
            }
        }
    }

    for (int i = 0; i < n; i++) {
        /* ", " ставим ПЕРЕД именем, кроме первого: лишней запятой в конце не будет. */
        if (i > 0) {
            printf(", ");
        }
        printf("%s", students[i].name);
    }

    return 0;
}