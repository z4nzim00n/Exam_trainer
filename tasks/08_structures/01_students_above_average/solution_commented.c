/*
 * Студенты выше среднего балла.
 *
 * Читаем всех студентов, считаем средний балл,
 * затем выводим имена тех, у кого оценка выше среднего.
 */

#include <stdio.h>

/* Структура: имя и оценка. typedef позволяет писать просто Student. */
typedef struct {
    char name[100]; /* 99 символов + '\0' */
    int rate;
} Student;

int main(void) {
    int n;

    /* Не прочиталось число или оно меньше 1 — ошибка. */
    if (scanf("%d", &n) != 1 || n < 1) {
        printf("n/a");
        return 0;
    }

    /* Массив из n структур. Размер известен только во время работы — это допустимо в C11. */
    Student students[n];
    long sum = 0; /* сумма всех оценок */

    for (int i = 0; i < n; i++) {
        /*
         * %99s читает слово (не больше 99 символов) и пропускает пробелы и переводы строк.
         * Перед name нет &: имя массива уже является адресом.
         * Перед rate & нужен: туда записывается число.
         */
        if (scanf("%99s", students[i].name) != 1 || scanf("%d", &students[i].rate) != 1) {
            printf("n/a");
            return 0;
        }
        sum += students[i].rate;
    }

    /* (double) нужен, чтобы деление не было целочисленным. */
    double avg = (double)sum / n;
    int first = 1; /* 1, пока ни одно имя не напечатано */

    for (int i = 0; i < n; i++) {
        if (students[i].rate > avg) {
            /* ", " печатаем ПЕРЕД именем, кроме первого: лишней запятой в конце не будет. */
            if (!first) {
                printf(", ");
            }
            printf("%s", students[i].name);
            first = 0;
        }
    }

    return 0;
}