/*
 * EXAM_09_06_ALT. Шифр Цезаря для файла (вывод в stdout).
 *
 * Читаем файл по одному символу, шифруем буквы и сразу печатаем.
 * Файл не меняется.
 */

#include <stdio.h>

int main(void) {
    char path[256];
    int shift;

    /* Один scanf читает путь и ключ и возвращает, сколько значений прочитал. Нужно два. */
    if (scanf("%255s %d", path, &shift) != 2) {
        printf("n/a");
        return 0;
    }

    /* "r" — только чтение. Если файла нет, fopen вернёт NULL. */
    FILE* file = fopen(path, "r");
    if (file == NULL) {
        printf("n/a");
        return 0;
    }

    /*
     * Приводим ключ к диапазону 0..25.
     * В C остаток от деления отрицательного числа тоже отрицательный (-1 % 26 == -1),
     * поэтому для отрицательного результата добавляем 26: ключ -1 равен ключу 25.
     */
    shift = shift % 26;
    if (shift < 0) {
        shift += 26;
    }

    int c; /* int, а не char: так отличается EOF */
    while ((c = fgetc(file)) != EOF) {
        if (c >= 'a' && c <= 'z') {
            /*
             * c - 'a' — номер буквы (0..25), + shift сдвигает,
             * % 26 зацикливает алфавит, 'a' + ... возвращает код буквы.
             */
            c = 'a' + (c - 'a' + shift) % 26;
        } else if (c >= 'A' && c <= 'Z') {
            c = 'A' + (c - 'A' + shift) % 26;
        }
        /* Остальные символы не трогаем, в том числе '\n'. */
        putchar(c);
    }

    fclose(file);

    return 0;
}