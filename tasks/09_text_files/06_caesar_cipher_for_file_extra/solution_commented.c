/*
 * EXAM_09_06. Шифр Цезаря для файла.
 *
 * Читаем весь файл в массив, шифруем буквы прямо в массиве,
 * затем записываем массив обратно в тот же файл.
 */

#include <stdio.h>

int main(void) {
    char path[256];
    int shift;

    /* Один scanf читает путь и сдвиг и возвращает, сколько значений прочитал. Нужно два. */
    if (scanf("%255s %d", path, &shift) != 2) {
        printf("n/a");
        return 0;
    }

    /* "r+" — открыть существующий файл и для чтения, и для записи. Если файла нет, fopen вернёт NULL. */
    FILE* file = fopen(path, "r+");
    if (file == NULL) {
        printf("n/a");
        return 0;
    }

    /*
     * Читаем до 1000 байт. fread возвращает, сколько байт прочитано.
     * 0 — файл пустой. 1000 — файл не поместился (больше 999 байт). Оба случая — ошибка.
     * Массив на 1001 байт — запас, чтобы не выходить за границы.
     */
    char text[1001];
    size_t n = fread(text, 1, 1000, file);

    if (n == 0 || n == 1000) {
        printf("n/a");
        fclose(file); /* файл закрываем и в ветке с ошибкой */
        return 0;
    }

    /*
     * Приводим сдвиг к диапазону 0..25.
     * % 26 даёт -25..25, а для отрицательного добавляем 26:
     * сдвиг на -1 равен сдвигу на 25 (остаток от деления на отрицательное в C тоже отрицательный).
     */
    shift = shift % 26;
    if (shift < 0) {
        shift += 26;
    }

    for (size_t i = 0; i < n; i++) {
        if (text[i] >= 'a' && text[i] <= 'z') {
            /*
             * Номер буквы в алфавите: text[i] - 'a' (0..25).
             * Прибавляем сдвиг, % 26 зацикливает алфавит (после z снова a),
             * 'a' + ... возвращает код буквы.
             */
            text[i] = 'a' + (text[i] - 'a' + shift) % 26;
        } else if (text[i] >= 'A' && text[i] <= 'Z') {
            text[i] = 'A' + (text[i] - 'A' + shift) % 26;
        }
        /* Остальные символы не трогаем. */
    }

    /*
 * ВАРИАНТ С ВЫВОДОМ В STDOUT.
 * Если по условию зашифрованный текст нужно ещё и вывести на экран,
 * раскомментируйте строку ниже. Используем fwrite, а не printf("%s"):
 * массив text после fread не завершён символом '\0', поэтому длину берём из n.
 *
 * Если файл менять НЕ нужно (только вывод), удалите rewind и второй fwrite
 * (тот, что пишет в file) и откройте файл в режиме "r" вместо "r+".
 */
    /* fwrite(text, 1, n, stdout); */

    /*
     * Возвращаемся в начало файла и записываем весь массив поверх старого содержимого.
     * Размер не изменился (n байт), поэтому "хвоста" от старого текста не остаётся.
     */

    /*
     * Возвращаемся в начало файла и записываем весь массив поверх старого содержимого.
     * Размер не изменился (n байт), поэтому "хвоста" от старого текста не остаётся.
     */
    rewind(file);
    fwrite(text, 1, n, file);
    fclose(file);

    return 0;
}