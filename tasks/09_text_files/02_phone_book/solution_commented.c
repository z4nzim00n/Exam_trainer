/*
 * EXAM_09_02. Телефонный справочник.
 *
 * План из двух проходов по файлу:
 *   1) проверяем ВСЕ строки (ничего не печатаем);
 *   2) если всё верно, печатаем.
 * Иначе при ошибке в конце файла мы уже напечатали бы начало,
 * а по условию при любой ошибке должно быть только "n/a".
 */

#include <stdio.h>
#include <string.h>

int main(void) {
    char path[256];
    char line[256];

    /* %255s читает слово без пробелов (не больше 255 символов) и сам пропускает '\n'. */
    if (scanf("%255s", path) != 1) {
        printf("n/a");
        return 0;
    }

    /* Открываем файл. Если его нет, fopen вернёт NULL. */
    FILE* file = fopen(path, "r");
    if (file == NULL) {
        printf("n/a");
        return 0;
    }

    /* Маска телефона: 'd' — любая цифра, остальные символы должны совпасть. */
    const char* mask = "8-ddd-ddd-dd-dd";
    int count = 0; /* сколько строк прочитали */
    int ok = 1;    /* пока ошибок нет */

    /* ПРОХОД 1: проверка. fgets вернёт NULL, когда строки кончились. */
    while (ok && fgets(line, sizeof(line), file) != NULL) {
        /* strcspn находит позицию '\n' (или конец строки). Ставим туда '\0' — переноса больше нет. */
        line[strcspn(line, "\n")] = '\0';

        /* Двоеточие должно быть, имя перед ним не пустое, телефон после него — ровно 15 символов. */
        const char* colon = strchr(line, ':');
        if (colon == NULL || colon == line || strlen(colon + 1) != 15) {
            ok = 0;
        } else {
            const char* phone = colon + 1;
            /* Сравниваем телефон с маской символ за символом. */
            for (int i = 0; i < 15; i++) {
                if (mask[i] == 'd') {
                    if (phone[i] < '0' || phone[i] > '9') {
                        ok = 0;
                    }
                } else if (phone[i] != mask[i]) {
                    ok = 0;
                }
            }
        }
        count++;
    }

    /* Ошибка в строке или пустой файл (count == 0) — выводим n/a. Файл закрываем в любом случае. */
    if (!ok || count == 0) {
        printf("n/a");
        fclose(file);
        return 0;
    }

    /* ПРОХОД 2: возвращаемся в начало файла и печатаем. */
    rewind(file);
    count = 0;

    while (fgets(line, sizeof(line), file) != NULL) {
        line[strcspn(line, "\n")] = '\0';

        char* colon = strchr(line, ':');
        char* phone = colon + 1;

        /* Заменяем ':' на '\0': теперь line — это только имя, и %s напечатает его. */
        *colon = '\0';

        /* '\n' ставим ПЕРЕД каждой строкой, кроме первой: после последней переноса не будет. */
        if (count > 0) {
            printf("\n");
        }

        /*
         * Телефон "8-950-111-22-33", индексы с нуля:
         * phone + 2  → "950" (код), берём 3 символа;
         * phone + 6  → "111", берём 3 символа;
         * phone + 10 → "22", берём 2 символа;
         * phone + 13 → "33", берём 2 символа.
         * %.3s и %.2s печатают не больше 3 или 2 символов.
         */
        printf("%s +7(%.3s)%.3s-%.2s-%.2s", line, phone + 2, phone + 6, phone + 10, phone + 13);
        count++;
    }

    fclose(file);

    return 0;
}