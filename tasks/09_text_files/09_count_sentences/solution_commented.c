/*
 * EXAM_09_09. Подсчёт предложений.
 *
 * Читаем файл по одному символу. Помним, была ли в текущем предложении
 * буква или цифра. Когда встречаем . ! ? после текста, предложение закончилось.
 */

#include <stdio.h>

int main(void) {
    char path[256];

    if (scanf("%255s", path) != 1) {
        printf("n/a");
        return 0;
    }

    FILE* file = fopen(path, "r");
    if (file == NULL) {
        printf("n/a");
        return 0;
    }

    int count = 0;    /* сколько предложений нашли */
    int has_text = 0; /* 1, если в текущем предложении уже была буква или цифра */
    int c;            /* int, а не char: так отличается EOF */

    while ((c = fgetc(file)) != EOF) {
        if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')) {
            /* Буква или цифра: в предложении есть содержимое. */
            has_text = 1;
        } else if (c == '.' || c == '!' || c == '?') {
            /*
             * Знак конца. Считаем предложение, только если перед ним был текст.
             * После подсчёта has_text = 0, поэтому остальные знаки группы ("???", "...", "!?")
             * не считаются повторно, и строка из одних знаков ("...") предложением не является.
             */
            if (has_text) {
                count++;
                has_text = 0;
            }
        }
        /* Пробелы, переводы строк и другие символы ни на что не влияют. */
    }

    fclose(file);

    printf("%d", count);

    return 0;
}