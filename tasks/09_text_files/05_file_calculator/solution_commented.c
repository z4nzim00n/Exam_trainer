/*
 * EXAM_09_05. Простой подсчёт (калькулятор из файла).
 *
 * Файл читаем по одному символу. Внешний цикл — по строкам,
 * внутренний — по символам одной строки. Выражение считаем на лету,
 * поэтому хранить строку целиком не нужно.
 */

#include <stdio.h>

int main(void) {
    char path[256];

    /* %255s читает путь (слово без пробелов) и сам пропускает '\n'. */
    if (scanf("%255s", path) != 1) {
        printf("n/a");
        return 0;
    }

    FILE* file = fopen(path, "r");
    if (file == NULL) {
        printf("n/a");
        return 0;
    }

    int count = 0; /* сколько строк-выражений обработано */

    /* fgetc возвращает int: код символа или EOF. Поэтому c — int, а не char. */
    int c = fgetc(file);

    /* Внешний цикл: одна итерация — одна строка файла. */
    while (c != EOF) {
        long long total = 0;  /* сумма уже обработанных слагаемых */
        long long number = 0; /* число, которое читаем сейчас */
        int sign = 1;         /* знак перед текущим числом: +1 или -1 */
        int digits = 0;       /* сколько цифр в текущем числе */
        int ok = 1;           /* пока ошибок в строке нет */

        /*
         * Внутренний цикл: символы до конца строки.
         * При ошибке цикл НЕ прерываем, а дочитываем строку до '\n':
         * иначе остаток плохой строки попадёт в следующую.
         */
        while (c != EOF && c != '\n') {
            if (c >= '0' && c <= '9') {
                digits++;
                if (digits > 9) {
                    ok = 0; /* слишком длинное число */
                } else {
                    /* Приписываем цифру справа: 12 и цифра 3 → 123. */
                    number = number * 10 + (c - '0');
                }
            } else if ((c == '+' || c == '-') && digits > 0) {
                /*
                 * Операция допустима только сразу после числа (digits > 0).
                 * Это отсекает "+1" (в начале) и "1++1", "1--1" (две подряд).
                 * Прибавляем число к итогу с его знаком и запоминаем знак для следующего.
                 */
                total += sign * number;
                sign = (c == '+') ? 1 : -1;
                number = 0;
                digits = 0;
            } else {
                /* Пробел, буква, '\r' и любой другой символ. */
                ok = 0;
            }
            c = fgetc(file);
        }

        /* Строка должна заканчиваться числом: пустая строка или "1+" — ошибка. */
        if (digits == 0) {
            ok = 0;
        }

        /* Последнее число ещё не прибавлено. */
        total += sign * number;

        /* ", " печатаем ПЕРЕД каждым результатом, кроме первого: лишней запятой в конце не будет. */
        if (count > 0) {
            printf(", ");
        }
        if (ok) {
            printf("%lld", total);
        } else {
            printf("n/a");
        }
        count++;

        /*
         * Если остановились на '\n', переходим к первому символу следующей строки.
         * Если файл закончился на '\n', следующим будет EOF, и внешний цикл завершится:
         * пустая строка после последнего '\n' не создаётся.
         */
        if (c == '\n') {
            c = fgetc(file);
        }
    }

    fclose(file);

    /* Не было ни одной строки (пустой файл) — общая ошибка. */
    if (count == 0) {
        printf("n/a");
    }

    return 0;
}